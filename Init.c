void initCharger(void){_daopc=0b11100001;_opvos=0b10000000;u8 i,A_SR01=0,A_SR02=0;
	for(i=63;i>0;i--){_opvos++;GCC_DELAY(1000);if(!_opo){A_SR01=_opvos&0b00111111;break; } }
	_opvos=0b10111111;
	for(i=63;i>0;i--){_opvos--;GCC_DELAY(1000);{A_SR02=_opvos&0b00111111;break; } }
	_opvos=(A_SR01+A_SR02)/2;_da1=CV_OUT_DIG;_da0=CC_OUT_DIG;
}
