void initEEPROMset(void){
		cal_CV=CV_OUT_DIG;
		cal_TC=TC_OUT_DIG;
		cal_CC=CC_OUT_DIG;
		adc_v_err=1;
		adc_i_err=1;
		if(ReadEEPROM(EEP_AD_CV+1))cal_CV=ReadEEPROM(EEP_AD_CV);
		if(ReadEEPROM(EEP_AD_CC+1))cal_CC=ReadEEPROM(EEP_AD_CC);
		if(ReadEEPROM(EEP_AD_TC+1))cal_TC=ReadEEPROM(EEP_AD_TC);
//		if(ReadEEPROM(EEP_AD_TC+1))cal_TC=EEP_VAL_Read(EEP_AD_TC);
		if(ReadEEPROM(EEP_AD_VE+1)){adc_v_err=(float)V_ADC_CALIB_DIG/(float)ReadEEPROM(EEP_AD_VE);
			/*if(adc_v_err>=1){cal_CC=(float)cal_CC*(float)adc_v_err;cal_TC=(float)cal_TC*(float)adc_v_err; }
			else{cal_CC=((float)cal_CC/(float)adc_v_err);cal_TC=((float)cal_TC/(float)adc_v_err); }*/ };
		if(ReadEEPROM(EEP_AD_CE+1)){adc_i_err=(float)I_ADC_CALIB_DIG/(float)ReadEEPROM(EEP_AD_CE); };
}
